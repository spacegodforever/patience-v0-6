"""`patience` command-line tool.

  patience init [--admin NAME] [--agent NAME ...] [--generate-password] [--pin] [--force]
      Creates the first admin approver, agent API keys, a local policy.yaml (copy of the
      default) and a .env with a fresh PATIENCE_LINK_SECRET. Secrets are shown ONCE.
  patience add-approver NAME [--role approver|admin] [--generate-password] [--pin]
  patience add-agent NAME
  patience verify-audit
  patience reconcile [--min-age SECONDS]
  patience version
"""
from __future__ import annotations
import argparse
import getpass
import os
import secrets
import shutil
import string
import sys
from pathlib import Path

VERSION = "0.6"
HERE = Path(__file__).resolve().parent


def _gen_password() -> str:
    alpha = string.ascii_letters + string.digits
    return "-".join("".join(secrets.choice(alpha) for _ in range(5)) for _ in range(4))


def _gen_pin() -> str:
    return "".join(secrets.choice(string.digits) for _ in range(6))


def _password(args, user) -> tuple[str, bool]:
    if args.generate_password or not sys.stdin.isatty():
        return _gen_password(), True
    while True:
        pw = getpass.getpass(f"Password for {user} (10+ chars): ")
        if len(pw) >= 10 and pw == getpass.getpass("Repeat: "):
            return pw, False
        print("Too short or didn't match; try again.")


def _load_dotenv(path: Path):
    import envfile
    envfile.load(str(path))


def cmd_init(args) -> int:
    import approvers, identity
    env = Path(args.env_file)
    if not env.exists():
        policy = Path(args.policy).resolve()
        lines = [
            "# Generated by `patience init`. Keep this file private (it is in .gitignore).",
            f"PATIENCE_LINK_SECRET={secrets.token_urlsafe(48)}",
            f"PATIENCE_POLICY={policy}",
            "PATIENCE_EXECUTE_LIVE=0",
            "PATIENCE_PUBLIC_URL=http://127.0.0.1:8765",
        ]
        env.write_text("\n".join(lines) + "\n")
        os.chmod(env, 0o600)
        print(f"Wrote {env} (with a fresh PATIENCE_LINK_SECRET).")
    _load_dotenv(env)
    pol = Path(args.policy)
    if not pol.exists():
        shutil.copy(HERE / "policies" / "default.yaml", pol)
        print(f"Wrote default policy to {pol}.")
    existing = approvers.load()
    if args.admin in existing and not args.force:
        print(f"Approver '{args.admin}' already exists; use --force to reset it.")
    else:
        pw, shown = _password(args, args.admin)
        pin = _gen_pin() if args.pin else None
        approvers.add(args.admin, pw, "admin", pin=pin)
        print(f"Created admin '{args.admin}'.")
        if shown:
            print(f"  password: {pw}   (shown once)")
        if pin:
            print(f"  PIN for one-tap links: {pin}   (shown once)")
    for name in args.agent:
        print(f"Agent '{name}' API key (shown once): {identity.add_agent(name)}")
    print("\nNext: `make run` (or `docker compose up`), then open http://127.0.0.1:8501 and log in.")
    return 0


def cmd_add_approver(args) -> int:
    import approvers
    pw, shown = _password(args, args.name)
    pin = _gen_pin() if args.pin else None
    approvers.add(args.name, pw, args.role, pin=pin)
    print(f"Created {args.role} '{args.name}'." + (f" password: {pw}" if shown else "") + (f" PIN: {pin}" if pin else ""))
    return 0


def cmd_add_agent(args) -> int:
    import identity
    print(identity.add_agent(args.name))
    return 0


def cmd_verify(args) -> int:
    import audit
    r = audit.verify()
    print(f"OK: {r['records']} records, chain intact" if r["ok"] else f"TAMPERED: {r['error']}")
    return 0 if r["ok"] else 1


def cmd_reconcile(args) -> int:
    import reconcile
    from engine import Patience
    flagged = reconcile.reconcile(Patience(os.environ.get("PATIENCE_STATE_PATH", "patience_state.json")),
                                  "cli", args.min_age)
    print(f"Flagged {len(flagged)} stuck execution(s) as needs_review.")
    return 0


def main(argv=None) -> int:
    os.chdir(os.environ.get("PATIENCE_HOME", os.getcwd()))
    sys.path.insert(0, str(HERE))
    _load_dotenv(Path(os.environ.get("PATIENCE_DOTENV", ".env")))
    ap = argparse.ArgumentParser(prog="patience", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("init")
    i.add_argument("--admin", default="admin")
    i.add_argument("--agent", action="append", default=[])
    i.add_argument("--generate-password", action="store_true")
    i.add_argument("--pin", action="store_true", help="also create a 6-digit PIN for one-tap links")
    i.add_argument("--force", action="store_true")
    i.add_argument("--env-file", default=os.environ.get("PATIENCE_DOTENV", ".env"))
    i.add_argument("--policy", default="policy.yaml")
    a = sub.add_parser("add-approver")
    a.add_argument("name")
    a.add_argument("--role", default="approver", choices=["approver", "admin"])
    a.add_argument("--generate-password", action="store_true")
    a.add_argument("--pin", action="store_true")
    g = sub.add_parser("add-agent")
    g.add_argument("name")
    sub.add_parser("verify-audit")
    r = sub.add_parser("reconcile")
    r.add_argument("--min-age", type=float, default=300)
    sub.add_parser("version")
    args = ap.parse_args(argv)
    if args.cmd == "version":
        print(f"PATIENCE v{VERSION}")
        return 0
    return {"init": cmd_init, "add-approver": cmd_add_approver, "add-agent": cmd_add_agent,
            "verify-audit": cmd_verify, "reconcile": cmd_reconcile}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
